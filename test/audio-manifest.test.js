import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile, mkdtemp,writeFile,rm,symlink} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {checkRecords,checkAssets} from '../scripts/check-audio-manifest.mjs';
import {NORMALIZER} from '../scripts/glossary-metrics.mjs';
const schema=JSON.parse(await readFile(new URL('../docs/schemas/audio-segment.schema.json',import.meta.url)));
const template=JSON.parse(await readFile(new URL('../docs/templates/audio-segment.example.json',import.meta.url)));
function record() {
 const r=structuredClone(template);
 r.example_only=false;r.source={source_id:'synthetic-test',uri:'urn:synthetic:test',version:'1',retrieved_at:'2026-01-01T00:00:00Z'};
 r.rights={status:'approved',license:'Test generated bytes only',evidence_ref:'test/audio-manifest.test.js',consent_status:'not_required_with_basis',allowed_uses:['internal_evaluation','training'],retention_until:null};
 r.audio={...r.audio,raw_path:'sample.wav',raw_sha256:'a'.repeat(64),sample_rate_hz:16000,channels:1,duration_seconds:1,start_seconds:0,end_seconds:1};
 r.reference={raw_text:'',normalized_text:'',status:'human_verified',normalizer_version:NORMALIZER};r.split='validation';
 return r;
}
test('placeholder and malformed schema cannot qualify as real data',()=>{
 assert.ok(checkRecords([template],schema).length>0);
 assert.match(checkRecords([{...record(),extra:true}],schema).join(),/unknown field/);
 assert.match(checkRecords([{...record(),audio:null}],schema).join(),/invalid type/);
 assert.ok(checkRecords([],schema).length);
});
test('rights, reference normalization, retention and bounds fail closed',()=>{
 assert.deepEqual(checkRecords([record()],schema),[]);
 for(const change of [r=>r.rights.status='pending',r=>r.rights.evidence_ref=null,r=>r.rights.allowed_uses=[],r=>r.rights.retention_until='2000-01-01T00:00:00Z',r=>r.reference.status='machine_generated',r=>r.reference.normalized_text='unexpected',r=>r.audio.end_seconds=2,r=>r.audio.raw_sha256=null]) {
  const r=record();change(r);assert.ok(checkRecords([r],schema).length);
 }
});
test('overlapping sessions, audio, groups, speakers and text are detected across splits',()=>{
 const a=record(),b=record();b.segment_id='second';b.split='sealed_test';
 assert.match(checkRecords([a,b],schema).join(),/cross-split session overlap/);
 b.session_id='second';b.group_id='second';b.audio.raw_sha256='b'.repeat(64);
 assert.deepEqual(checkRecords([a,b],schema),[]);
 assert.match(checkRecords([a,b],schema,{speakerDisjoint:true}).join(),/speaker overlap/);
 a.reference.raw_text=a.reference.normalized_text='禱告';b.reference={...a.reference};
 assert.match(checkRecords([a,b],schema).join(),/cross-split text overlap/);
 b.split='train';assert.match(checkRecords([b],schema).join(),/evaluation requires/);
 assert.deepEqual(checkRecords([b],schema,{purpose:'training'}),[]);
 assert.match(checkRecords([a,b],schema,{purpose:'split_audit'}).join(),/cross-split text overlap/);
 b.reference.raw_text=b.reference.normalized_text='擘餅';
 assert.deepEqual(checkRecords([a,b],schema,{purpose:'split_audit',speakerDisjoint:false}),[]);
});
test('actual generated WAV is probed; tampering and root escapes are rejected',async()=>{
 const root=await mkdtemp(path.join(tmpdir(),'caption-manifest-'));
 try {
  const wav=Buffer.alloc(32044);wav.write('RIFF');wav.writeUInt32LE(32036,4);wav.write('WAVEfmt ',8);wav.writeUInt32LE(16,16);wav.writeUInt16LE(1,20);wav.writeUInt16LE(1,22);wav.writeUInt32LE(16000,24);wav.writeUInt32LE(32000,28);wav.writeUInt16LE(2,32);wav.writeUInt16LE(16,34);wav.write('data',36);wav.writeUInt32LE(32000,40);
  await writeFile(path.join(root,'sample.wav'),wav);
  const r=record();r.audio.raw_sha256=createHash('sha256').update(wav).digest('hex');
  assert.deepEqual(await checkAssets([r],root),[]);
  const manifest=path.join(root,'manifest.jsonl'),output=path.join(root,'report.json');
  await writeFile(manifest,JSON.stringify(r)+'\n');
  const args=[fileURLToPath(new URL('../scripts/check-audio-manifest.mjs',import.meta.url)),'--manifest',manifest,'--root',root,'--output',output];
  const run=spawnSync(process.execPath,args,{encoding:'utf8'});assert.equal(run.status,0,run.stderr);
  const report=JSON.parse(await readFile(output,'utf8'));assert.equal(report.status,'passed');assert.equal(report.assetsChecked,true);assert.equal(report.trainingRun,false);
  const again=spawnSync(process.execPath,args,{encoding:'utf8'});assert.equal(again.status,1,'report must never overwrite');

  r.audio.sample_rate_hz=22050;assert.equal((await checkAssets([r],root)).length,1);r.audio.sample_rate_hz=16000;
  r.audio.raw_sha256='f'.repeat(64);assert.equal((await checkAssets([r],root)).length,1);
  await symlink('/etc/hosts',path.join(root,'escape'));r.audio.raw_path='escape';assert.equal((await checkAssets([r],root)).length,1);
 } finally {await rm(root,{recursive:true,force:true});}
});

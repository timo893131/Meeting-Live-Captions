#!/usr/bin/env python3
"""Generate public/pinyin-zh.js for same-sound church-term correction in the browser.

Exports:
  PINYIN   {syllable: chars}  most common toned reading of each CJK char (U+4E00-U+9FFF)
  TERMS    {term: [[syllables of char 1], ...]}  accepted readings per char of each built-in term
           = phrase reading (via Simplified, so pypinyin's phrase data applies) + each char's primary reading
  PROTECT  real dictionary words that sound exactly like a term (戒嚴、照會、真言): never corrected
  COMMON   common 2-3 char words plus every 2-char word that could touch a term's first/last sound
           (Traditional, Taiwan) joined by '|': a correction is refused
           when it would rewrite a common word or break one across the window boundary (繼續、祭司、戒嚴)

Sources: pypinyin (MIT) readings; jieba dict.txt (MIT) word frequencies; OpenCC (Apache-2.0) conversion.
Usage: python scripts/build-pinyin-table.py [--common 20000]
"""
import argparse
import json
import os
import re
from collections import defaultdict
from pathlib import Path

import jieba
import pypinyin
from opencc import OpenCC
from pypinyin import Style, lazy_pinyin, pinyin

# Readings pypinyin gets wrong for these Recovery-Version terms (Taiwan usage).
OVERRIDES = {'約翰參書': 'yue1 han4 san1 shu1', '擘餅': 'bo4 bing3'}
# Dictionary words that sound like a term but are common misspellings of it: still corrected.
MISSPELLINGS = {'創世紀'}
PROTECT_MIN_FREQ = 20
BOUNDARY_MIN_FREQ = 20


def primary_reading(char):
    readings = pinyin(char, style=Style.TONE3, heteronym=True, neutral_tone_with_five=True, errors='ignore')
    syllables = [s for s in (readings[0] if readings else []) if s and s[-1].isdigit()]
    return syllables[0] if syllables else None


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--common', type=int, default=10000, help='Number of most frequent jieba words to keep')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    t2s, s2tw = OpenCC('t2s'), OpenCC('s2twp')

    groups = defaultdict(list); primary = {}
    for code in range(0x4E00, 0xA000):
        char = chr(code); syllable = primary_reading(char)
        if syllable:
            groups[syllable].append(char); primary[char] = syllable

    source = (root/'public/church-terms.js').read_text(encoding='utf-8')
    terms = sorted(set(re.findall(r"'([^']+)'", source)))
    readings = {}
    for term in terms:
        phrase = OVERRIDES.get(term, ' '.join(lazy_pinyin(t2s.convert(term), style=Style.TONE3,
                                                          neutral_tone_with_five=True))).split()
        if len(phrase) != len(term):
            raise SystemExit(f'Reading length mismatch for {term}: {phrase}')
        readings[term] = [sorted({p, primary.get(c, p)}) for c, p in zip(term, phrase)]

    # Real words that sound exactly like a term (戒嚴~介言, 照會~召會, 真言~箴言) are never rewritten.
    by_sound = {}
    for term, accepted in readings.items():
        by_sound.setdefault(tuple(primary.get(c) for c in term), set()).add(term)
    protect = set(); boundary = set()
    # Sounds a term can start/end with: a heard char with that sound may be glued to a neighbour (祭司、繼續).
    first_sounds = {s for r in readings.values() for s in r[0]}
    last_sounds = {s for r in readings.values() for s in r[-1]}
    entries = []
    for line in Path(os.path.join(os.path.dirname(jieba.__file__), 'dict.txt')).read_text(encoding='utf-8').splitlines():
        word, freq, *_ = line.split(' ')
        traditional = s2tw.convert(word)
        sound = tuple(primary.get(c) for c in traditional)
        if (sound in by_sound and traditional not in by_sound[sound] and traditional not in MISSPELLINGS
                and int(freq) >= PROTECT_MIN_FREQ):
            protect.add(traditional)
        if (len(traditional) == 2 and int(freq) >= BOUNDARY_MIN_FREQ
                and (primary.get(traditional[0]) in last_sounds or primary.get(traditional[1]) in first_sounds)):
            boundary.add(traditional)
        if 2 <= len(word) <= 3 and all('一' <= c <= '鿿' for c in word):
            entries.append((int(freq), word))
    common = []
    for _, word in sorted(entries, reverse=True):
        word = s2tw.convert(word)
        if len(word) in (2, 3) and word not in readings and word not in common:
            common.append(word)
        if len(common) >= args.common:
            break

    common = sorted((set(common) | boundary) - set(readings))
    body = (f'// Generated by scripts/build-pinyin-table.py (pypinyin {pypinyin.__version__}, jieba dict, OpenCC). Do not edit.\n'
            f'export const PINYIN = {json.dumps({k: "".join(v) for k, v in sorted(groups.items())}, ensure_ascii=False, separators=(",", ":"))};\n'
            f'export const TERMS = {json.dumps(readings, ensure_ascii=False, separators=(",", ":"))};\n'
            f'export const COMMON = {json.dumps("|".join(common), ensure_ascii=False)};\n'
            f'export const PROTECT = {json.dumps(sorted(protect), ensure_ascii=False)};\n')
    (root/'public/pinyin-zh.js').write_text(body, encoding='utf-8')
    print(f'{len(primary)} chars, {len(readings)} terms, {len(common)} common words, protected: {"、".join(sorted(protect))}')


if __name__ == '__main__':
    main()

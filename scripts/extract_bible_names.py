#!/usr/bin/env python3
"""Generate public/bible-names.js: Bible person/place names for same-sound caption correction.

Names are discovered automatically in the Recovery Version text (twgbr archive, recovery-version/text):
  * term candidates from extract_church_terms.py (frequency, cohesion, boundary entropy);
  * a transliteration-character test: names are written with a small set of sound-transcription characters
    (亞、撒、拿、利、米、勒…), seeded from well-known names below;
  * 3+ characters only (2-character names are high-risk for false same-sound edits; only the listed
    well-known 2-character names are kept), no phrases (說、到、王、人、地…), no common dictionary words,
    no Bible book names (already terms) and no vocative endings (耶路撒冷阿).
The output is a list of names only (facts), not Bible text. Never derive terms from a sealed test set.

Usage (two passes: the second drops names that edit already-correct text):
  python scripts/extract_bible_names.py --archive data/twgbr-archive-v2
  python scripts/build-pinyin-table.py
  node scripts/term-precision.mjs data/twgbr-archive-v2/recovery-version/text data/twgbr-archive-v2/life-study/text > precision.json
  python scripts/extract_bible_names.py --archive data/twgbr-archive-v2 --precision precision.json
  python scripts/build-pinyin-table.py
"""
import argparse
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'scripts'))
import extract_church_terms as et  # noqa: E402

SEED = ('亞伯拉罕 以撒 雅各 約瑟 摩西 亞倫 約書亞 撒母耳 掃羅 大衛 所羅門 以利亞 以利沙 但以理 耶利米 以賽亞 以西結 '
        '彼得 約翰 保羅 提摩太 巴拿巴 腓力 司提反 馬利亞 拉撒路 耶路撒冷 伯利恆 拿撒勒 加利利 撒瑪利亞 埃及 巴比倫 '
        '亞述 摩押 以東 非利士 迦南 約但 耶利哥 示劍 伯特利 希伯崙 基列 利未 猶大 便雅憫 以法蓮 瑪拿西 拿弗他利 '
        '西布倫 以薩迦 亞設 迦得 流便 西緬 法老 尼布甲尼撒 大利烏 古列 亞哈 耶洗別 拿俄米 路得 波阿斯 俄備得 '
        '耶西 拿單 押沙龍 米甲 約拿單 基甸 參孫 底波拉 巴拉 該亞 亞比米勒 以利米勒 瑪倫 基連 俄珥巴')
# Well-known two-character names kept despite the length rule.
TWO_CHAR = set('摩西 雅各 約瑟 掃羅 大衛 亞倫 以撒 彼得 約翰 保羅 腓力 法老 摩押 以東 迦南 埃及 亞述 基列 利未 猶大 '
               '流便 西緬 亞設 迦得 拿單 基甸 參孫 路得 瑪倫 基連 耶西 米甲 亞哈 古列 撒拉 利亞 拉結 亞伯 挪亞 '
               '亞當 夏娃 該隱 以掃 約伯 約拿 約珥 彌迦 那鴻 哈該 示巴 示劍 迦特 拿伯 雅億 拉麥'.split())
PHRASE_CHARS = set('說到在回帶屬照見對將各城的和了王人地家河山子孫眾諸祭話使一二三四五六七八九十百千萬')
PHRASE_PARTS = ('支派', '律法', '哥哥', '弟兄')
MIN_FREQ, MAX_DICT_FREQ = 5, 50


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--archive', default='data/twgbr-archive-v2')
    parser.add_argument('--output', default='public/bible-names.js')
    parser.add_argument('--precision', help='JSON from scripts/term-precision.mjs run on already-correct text')
    parser.add_argument('--max-false-edits', type=int, default=1,
                        help='Drop a name whose correction changed already-correct text more often than this')
    args = parser.parse_args()
    import jieba
    from opencc import OpenCC
    texts = sorted((Path(args.archive)/'recovery-version/text').glob('*.txt'))
    if len(texts) != 66:
        raise SystemExit(f'Expected 66 Recovery Version book texts, found {len(texts)}')
    docs = [dict(id=f.name, source_url=f.name, title=f.name, kind='bible', text_sha256='',
                 runs=et.CJK.findall(f.read_text(encoding='utf-8'))) for f in texts]
    ranked, _, _ = et.extract(docs, min_freq=MIN_FREQ, min_docs=1, limit=8000)
    s2tw = OpenCC('s2twp'); dictionary = {}
    for line in Path(os.path.dirname(jieba.__file__), 'dict.txt').read_text(encoding='utf-8').splitlines():
        word, freq, *_ = line.split(' ')
        word = s2tw.convert(word); dictionary[word] = max(int(freq), dictionary.get(word, 0))
    books = re.findall(r"'([^']+)'", (ROOT/'public/church-terms.js').read_text(encoding='utf-8'))
    translit = set(SEED.replace(' ', ''))
    names = set(TWO_CHAR)
    for row in ranked:
        term = row['term']
        share = sum(c in translit for c in term)/len(term)
        if (len(term) < 3 or share < 2/3 or term.endswith('阿') or any(c in PHRASE_CHARS for c in term) or any(p in term for p in PHRASE_PARTS)
                or dictionary.get(term, 0) >= MAX_DICT_FREQ or any(book in term or term in book for book in books)):
            continue
        names.add(term)
    dropped = []
    if args.precision:
        # Same-sound clashes (撒迦利亞/撒迦利雅, 示巴/是巴, 路得/路德=Luther) show up as edits of correct text.
        report = json.loads(Path(args.precision).read_text(encoding='utf-8'))
        dropped = sorted(n for n in names if report.get(n, {}).get('changes', 0) > args.max_false_edits)
        names -= set(dropped)
    # Seen on the Life-Study development set: speakers say 非利士 with s for sh (菲利斯), which matched 腓力斯 (Felix,
    # rare) and was rewritten wrongly; the Philistines are far more frequent.
    names -= {'腓力斯'}
    names = sorted(names - set(books), key=lambda n: (-len(n), n))
    if dropped:
        print('dropped (edits correct text):', '、'.join(dropped))
    body = ('// Generated by scripts/extract_bible_names.py from the Recovery Version text: Bible person/place\n'
            '// names (a list of names only, no Bible text). Used for same-sound caption correction.\n'
            f'export const BIBLE_NAMES = {json.dumps(names, ensure_ascii=False)};\n')
    Path(args.output).write_text(body, encoding='utf-8')
    print(f'{len(names)} names → {args.output}')


if __name__ == '__main__':
    main()
